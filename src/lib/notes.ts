/**
 * Access to the output of `scripts/compile.py`.
 *
 * `src/generated/notes.json` is the manifest (metadata + table of contents) and
 * `src/generated/notes/<slug>.html` holds the page body produced by Typst.
 * Neither is committed; run `./compile.sh` after editing blog.toml.
 *
 * Figures drawn in Typst arrive as inline `<svg>`; raster `#image(...)`s are
 * pulled out to `public/images/<slug>/` by the same script and referenced by
 * URL from inside the body.
 */
import manifest from "@/generated/notes.json";
import tokenCounts from "@/generated/token-counts.json";
import { htmlCjkCount } from "@/utils/wordCount";

export interface TocEntry {
  level: number;
  text: string;
  id: string;
}

/** One part of a series, as listed in its index. */
export interface SeriesPart {
  slug: string;
  title: string;
}

/**
 * A 「连载」 (series): several notes published out of one directory.
 *
 * `parts` is in reading order and comes from `blog.toml`, not from the page, so
 * the index is identical on every part. `index` is the 1-based position of the
 * note this manifest entry describes.
 */
export interface NoteSeries {
  id: string;
  title: string;
  index: number;
  parts: SeriesPart[];
}

export interface Note {
  slug: string;
  title: string;
  summary: string;
  tags: string[];
  /** `YYYY-MM-DD`; the only sort key of every listing. */
  date: string | null;
  project: string;
  kind: string;
  html: string;
  pdf: string;
  snapshot: string;
  series: NoteSeries | null;
  bytes: number;
  math: number;
  figures: number;
  images: number;
  toc: TocEntry[];
}

export interface Project {
  id: string;
  title: string;
  description: string;
  /** Only remaining curated order: the group order on the home page. */
  order: number;
}

interface Manifest {
  typstVersion: string;
  site: Record<string, string>;
  projects: Project[];
  notes: Note[];
}

const data = manifest as unknown as Manifest;

export const notes: Note[] = data.notes;
export const projects: Project[] = data.projects;
export const typstVersion: string = data.typstVersion;

/** Body HTML for a note, injected verbatim into the page. */
const rawBodies = import.meta.glob<string>("../generated/notes/**/*.html", {
  query: "?raw",
  import: "default",
  eager: true,
});

const bodies = new Map<string, string>();
for (const [key, body] of Object.entries(rawBodies)) {
  const slug = key
    .replace(/^.*\/generated\/notes\//, "")
    .replace(/\.html$/, "");
  bodies.set(slug, body);
}

export function noteBody(slug: string): string {
  const body = bodies.get(slug);
  if (!body) {
    throw new Error(
      `No generated HTML for "${slug}". Run ./compile.sh (or check blog.toml).`
    );
  }
  return body;
}

const cjkCounts = new Map<string, number>();

/**
 * Prose length of a note: CJK characters only, with code, equations and SVG
 * labels left out (see `@/utils/wordCount`). Computed from the generated HTML
 * once per build, then cached by slug.
 */
export function noteCjk(note: Note): number {
  const cached = cjkCounts.get(note.slug);
  if (cached !== undefined) return cached;

  const cjk = htmlCjkCount(noteBody(note.slug));
  cjkCounts.set(note.slug, cjk);
  return cjk;
}

interface TokenCounts {
  tokenizer: {
    model: string;
    revision: string;
    tokenizerSha256: string;
  };
  notes: Record<string, { tokens: number; files: string[] }>;
}

const tokenData = tokenCounts as unknown as TokenCounts;

/**
 * Tokens of the note's Typst source: the entry file plus its recursive
 * `#include` closure, with `#import`ed helper libraries left out. Generated by
 * `scripts/tokenize.mjs`; see that file for the exact rules.
 */
export function noteTokens(note: Note): number {
  const entry = tokenData.notes[note.slug];
  if (!entry) {
    throw new Error(
      `No token count for "${note.slug}". Run \`pnpm notes\` after compiling.`
    );
  }
  return entry.tokens;
}

export function projectOf(note: Note): Project {
  return (
    projects.find(p => p.id === note.project) ?? {
      id: note.project,
      title: note.project,
      description: "",
      order: 999,
    }
  );
}
